#[test]
fn ed25519_spki_is_byte_exact_with_reference() {
    let der = pem_decode("PUBLIC KEY", ED_SPKI_PEM).unwrap();
    assert_eq!(ed25519_public_from_spki(&der).unwrap(), ED_PUBLIC);
    assert_eq!(ed25519_public_to_spki(&ED_PUBLIC).to_vec(), der);
    assert_eq!(pem_encode("PUBLIC KEY", &der), ED_SPKI_PEM);
}

#[test]
fn ed25519_pkcs8_is_byte_exact_with_reference() {
    let der = pem_decode("PRIVATE KEY", ED_PKCS8_PEM).unwrap();
    assert_eq!(ed25519_seed_from_pkcs8(&der).unwrap(), ED_SEED);
    assert_eq!(ed25519_seed_to_pkcs8(&ED_SEED).to_vec(), der);
    assert_eq!(pem_encode("PRIVATE KEY", &der), ED_PKCS8_PEM);
}

#[test]
fn rsa_spki_is_byte_exact_with_reference() {
    let der = pem_decode("PUBLIC KEY", RSA_SPKI_PEM).unwrap();
    assert_eq!(rsa_public_to_spki(RSA_N, RSA_E), der);
    assert_eq!(pem_encode("PUBLIC KEY", &der), RSA_SPKI_PEM);
    let key = rsa_public_from_spki(&der).unwrap();
    assert_eq!(key.modulus_be(), RSA_N);
    assert_eq!(key.exponent_be(), RSA_E);
}
