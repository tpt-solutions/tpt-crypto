#[test]
fn pkcs8_rejects_mismatched_public_key() {
    // Flip one byte inside the advertised public point (last byte of the DER).
    let mut bad = P256_PKCS8.to_vec();
    let last = bad.len() - 1;
    bad[last] ^= 1;
    assert!(p256_private_from_pkcs8(&bad).is_err());
}

#[test]
fn spki_rejects_wrong_curve_oid() {
    // A P-384 SPKI must not parse as P-256.
    assert!(p256_public_from_spki(P384_SPKI).is_err());
    assert!(p384_public_from_spki(P256_SPKI).is_err());
}
