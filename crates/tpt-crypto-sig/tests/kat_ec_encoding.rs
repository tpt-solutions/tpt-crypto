fn p256_spki_is_byte_exact_with_reference() {
    let vk = p256_public_from_spki(P256_SPKI).unwrap();
    assert_eq!(p256_public_to_spki(&vk), P256_SPKI);
}

#[test]
fn p256_pkcs8_is_byte_exact_with_reference() {
    let sk = p256_private_from_pkcs8(P256_PKCS8).unwrap();
    assert_eq!(sk.to_be_bytes().expose_secret()[..32], P256_D);
    assert_eq!(p256_private_to_pkcs8(&sk), P256_PKCS8);
    // The public key derived from the scalar matches the reference SPKI.
    assert_eq!(p256_public_to_spki(&sk.verifying_key()), P256_SPKI);
}

