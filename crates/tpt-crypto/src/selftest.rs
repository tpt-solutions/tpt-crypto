//! Power-on known-answer self-test.
//!
//! [`run`] checks one published vector for each classical primitive the facade
//! exposes, and returns [`Error::Verification`] on the first mismatch. Call it
//! once at start-up in environments that need an integrity check of the build
//! (for example a firmware image or a FIPS-style deployment).
//!
//! The vectors are inlined rather than read from disk, so the check works in
//! `no_std` builds with no filesystem. Sources:
//!
//! * SHA-256 of `"abc"`: FIPS 180-4 example.
//! * HMAC-SHA-256: RFC 4231 test case 2.
//! * HKDF-SHA-256: RFC 5869 test case 1.
//! * X25519: RFC 7748 §6.1 shared secret.
//! * Ed25519: RFC 8032 §7.1 test 1 (empty message).

