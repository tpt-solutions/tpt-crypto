fn check(ok: bool) -> Result<()> {
    if ok {
        Ok(())
    } else {
        Err(Error::Verification)
    }
}

/// Run the power-on known-answer checks.
///
/// Returns `Ok(())` when every primitive reproduces its published vector, and
/// [`Error::Verification`] otherwise.
pub fn run() -> Result<()> {
    // SHA-256.
    check(sha256(b"abc") == SHA256_ABC)?;

    // HMAC-SHA-256.
    check(hmac_sha256(b"Jefe", b"what do ya want for nothing?") == HMAC_RFC4231_2)?;

    // HKDF-SHA-256 (RFC 5869 case 1).
    let ikm = [0x0bu8; 22];
    let salt: [u8; 13] = core::array::from_fn(|i| i as u8);
    let info: [u8; 10] = core::array::from_fn(|i| 0xf0 + i as u8);
    let mut okm = [0u8; 42];
    hkdf_sha256(&salt, &ikm, &info, &mut okm);
    check(okm == HKDF_RFC5869_1)?;

    // X25519: both sides derive the same RFC 7748 shared secret.
    let base = {
        let mut b = [0u8; 32];
        b[0] = 9;
        b
    };
    let alice_pub = X25519::diffie_hellman(&X25519_ALICE_PRIV, &base);
    let bob_pub = X25519::diffie_hellman(&X25519_BOB_PRIV, &base);
    check(X25519::diffie_hellman(&X25519_ALICE_PRIV, &bob_pub) == X25519_SHARED)?;
    check(X25519::diffie_hellman(&X25519_BOB_PRIV, &alice_pub) == X25519_SHARED)?;

    // Ed25519: derivation, deterministic signing and verification.
    let sk = SigningKey::from_seed(ED25519_SEED);
    check(sk.verifying_key().to_bytes() == ED25519_PUBLIC)?;
    check(sk.sign(b"").to_bytes() == ED25519_SIG_EMPTY)?;
    let vk = VerifyingKey::from_bytes(&ED25519_PUBLIC)?;
    vk.verify(b"", &Signature::from_bytes(ED25519_SIG_EMPTY))?;

    Ok(())
}

